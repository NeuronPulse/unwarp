/**
 * Dev harness: measure how faithfully unwarp rebuilds blocks from 02scratch-vm compiled data.
 *
 * Pipeline (mirrors 02packager):
 *   original.sb3  --(02scratch-vm compileProjectFromJSON)-->  compiled.json
 *   original.sb3  --(strip blocks, as cloneCompiledTargetSnapshot does)-->  stripped project.json
 *   stripped + compiled  --(unwarp rebuildProjectJSON)-->  rebuilt blocks
 *   rebuilt blocks  vs  original blocks   -> report
 *
 * Usage: npx tsx tools/roundtrip-report.ts <original.sb3> <compiled.json> [--verbose]
 */
import fs from 'fs';
import { createRequire } from 'module';
import { rebuildProjectJSON } from '../src/unpackager/index';

const require = createRequire(import.meta.url);
const JSZip = require('@turbowarp/jszip');

const [origPath, compiledPath] = process.argv.slice(2);
if (!origPath || !compiledPath) {
    console.error('usage: npx tsx tools/roundtrip-report.ts <original.sb3> <compiled.json>');
    process.exit(1);
}

async function main() {
const zip = await JSZip.loadAsync(fs.readFileSync(origPath));
const origJSON = JSON.parse(await zip.file('project.json').async('string'));
const compiled = JSON.parse(fs.readFileSync(compiledPath, 'utf8'));

// --- strip exactly like 02scratch-vm's cloneCompiledTargetSnapshot -----------
const stripped = JSON.parse(JSON.stringify(compiled.targets ? { ...origJSON, targets: compiled.targets } : origJSON));
// compiled.targets already has blocks={} and comments filtered, so use it directly when present.
if (!compiled.targets) {
    for (const t of stripped.targets) {
        t.blocks = {};
        t.comments = {};
    }
}

const { warnings, rebuiltTargets } = rebuildProjectJSON(stripped, compiled);

// --- comparison -------------------------------------------------------------
// Block ids are regenerated by the serializer, so compare trees structurally:
// canonicalise each top-level script into a nested opcode tree and compare multisets.

type Canon = { op: string; fields: Record<string, string>; inputs: Record<string, Canon | Canon[] | string>; substacks: Record<string, Canon[]> };

function canonise(blocks: Record<string, any>, id: string, seen: Set<string>): Canon | string {
    const b = blocks[id];
    if (!b) return `<?${id}>`;
    if (seen.has(id)) return '<cycle>';
    seen.add(id);

    const fields: Record<string, string> = {};
    for (const [k, v] of Object.entries(b.fields || {})) fields[k] = String((v as any).value ?? v);

    const inputs: Record<string, any> = {};
    for (const [k, v] of Object.entries(b.inputs || {})) {
        inputs[k] = canoniseInput(blocks, v as any, seen);
    }

    return { op: b.opcode, fields, inputs };
}

function canoniseInput(blocks: Record<string, any>, v: any, seen: Set<string>): any {
    // sb3 input value: [shadowType, payload] or [shadowType, payload, obscured]
    const arr = v as any[];
    const payload = arr[1];
    if (Array.isArray(payload)) {
        // literal: [type, value] e.g. [4, "10"] / [10, "hi"] / [5, [1,"#ff0000"]]
        const t = payload[0];
        const val = payload[1];
        if (t === 1) {
            // variable / list reference: [1, [12, "name", "id"]] or broadcast [1,[11,"name","id"]]
            const inner = val as any[];
            return { ref: inner[0], name: String(inner[1]) };
        }
        if (t === 3) {
            // [[3, substackId, obscured]] -- handled by parent; here it's a nested array of block id
            return { sub: canonise(blocks, String(val[0]), seen) };
        }
        if (t === 2 || t === 3) {
            // obscured input pointing at a block id? (2 = block no shadow)
            return { sub: canonise(blocks, String(val), seen) };
        }
        return { lit: t, v: String(val) };
    }
    if (typeof payload === 'string') {
        return { sub: canonise(blocks, payload, seen) };
    }
    return { raw: String(payload) };
}

/**
 * Some sb3 files (and every project unwarp rebuilds) omit the redundant `id` property inside
 * each block object, relying on the map key instead. Normalise so lookups by id always work.
 */
function withIds(blocks: Record<string, any>): Record<string, any> {
    const out: Record<string, any> = {};
    for (const [key, b] of Object.entries(blocks)) out[key] = { ...b, id: b.id ?? key };
    return out;
}

function topLevelTrees(blocks: Record<string, any>): string[] {
    const map = withIds(blocks);
    const roots = Object.values(map).filter((b: any) => b.topLevel);
    return roots.map((b: any) => JSON.stringify(canonise(map, b.id, new Set())));
}

function countBlocks(blocks: Record<string, any>): Map<string, number> {
    const m = new Map<string, number>();
    for (const b of Object.values(blocks) as any[]) {
        if (b.shadow) continue; // shadows are regenerated, not comparable
        m.set(b.opcode, (m.get(b.opcode) ?? 0) + 1);
    }
    return m;
}

console.log(`\n=== ${origPath} ===`);
console.log(`rebuilt targets: ${rebuiltTargets}`);
if (warnings.length) {
    console.log(`\n--- warnings (${warnings.length}) ---`);
    for (const w of warnings.slice(0, 40)) console.log('  ! ' + w);
    if (warnings.length > 40) console.log(`  ... and ${warnings.length - 40} more`);
}

for (let i = 0; i < origJSON.targets.length; i++) {
    const name = origJSON.targets[i].name;
    const ob = origJSON.targets[i].blocks || {};
    const nb = stripped.targets[i].blocks || {};
    const oc = countBlocks(ob);
    const nc = countBlocks(nb);

    const allOps = new Set([...oc.keys(), ...nc.keys()]);
    const diffs: string[] = [];
    let lost = 0, extra = 0;
    for (const op of allOps) {
        const a = oc.get(op) ?? 0, b = nc.get(op) ?? 0;
        if (a !== b) {
            diffs.push(`    ${op}: orig=${a} rebuilt=${b} (${b < a ? 'LOST ' + (a - b) : 'EXTRA ' + (b - a)})`);
            if (b < a) lost += a - b; else extra += b - a;
        }
    }
    const ot = topLevelTrees(ob), nt = topLevelTrees(nb);
    const scriptMatch = ot.length === nt.length;
    if (process.env.DIFF) {
        // Pair scripts up in order and show the first structural divergence of each pair.
        for (let k = 0; k < Math.max(ot.length, nt.length); k++) {
            const a = ot[k], b = nt[k];
            if (a === b) continue;
            console.log(`\n  --- script #${k} differs ---`);
            if (!a) { console.log('  orig: <missing>\n  rebuilt: ' + (b || '').slice(0, 900)); continue; }
            if (!b) { console.log('  orig: ' + a.slice(0, 900) + '\n  rebuilt: <missing>'); continue; }
            let p = 0;
            while (p < a.length && p < b.length && a[p] === b[p]) p++;
            console.log('  orig   ...' + a.slice(Math.max(0, p - 160), p + 240));
            console.log('  rebuilt...' + b.slice(Math.max(0, p - 160), p + 240));
        }
    }

    console.log(`\n[${i}] ${name}: orig blocks=${Object.keys(ob).length} rebuilt=${Object.keys(nb).length}` +
        `  scripts orig=${ot.length} rebuilt=${nt.length}${scriptMatch ? '' : '  <-- SCRIPT COUNT MISMATCH'}` +
        `${lost ? `  LOST=${lost}` : ''}${extra ? `  EXTRA=${extra}` : ''}`);
    if (diffs.length) console.log(diffs.join('\n'));
}
}

main().catch(e => { console.error(e); process.exit(1); });
